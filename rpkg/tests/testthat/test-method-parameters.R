test_that("inherent parameter attributes reach formals, checks and conversion", {
  obj <- ParameterOptions$new()
  expect_identical(obj$mode(), "safe")
  expect_identical(obj$mode("careful"), "safe")
  expect_identical(obj$modes(c("f", "s")), c("fast", "safe"))
  expect_identical(obj$labels(c("f", "s")), c("fast", "safe"))
  expect_error(obj$labels(), "missing")
  expect_identical(obj$checked(2), 2L)
  expect_error(obj$checked(NA_real_), class = "rust_error")
  expect_identical(obj$defaulted(), 7L)
  expect_identical(obj$converted(2), 2)
  unchecked <- tryCatch(obj$unchecked("bad"), error = identity)
  rechecked <- tryCatch(obj$rechecked("bad"), error = identity)
  expect_identical(unchecked$kind, "conversion")
  expect_identical(unchecked$rust_type, "i32")
  expect_identical(rechecked$kind, "conversion")
  expect_null(rechecked$rust_type)
  expect_identical(obj$classes(structure(2, class = "allowed")), 2)
  expect_error(obj$classes(2), class = "rust_error")
  expect_error(obj$classes(structure(2, class = c("allowed", "blocked"))), class = "rust_error")
})

test_that("trait implementation and declaration parameter options reach wrappers", {
  obj <- ParameterOptions$new()
  methods <- ParameterOptions$ParameterTrait
  expect_identical(methods$declared(obj), "fast")
  expect_identical(methods$declared(obj, "s"), "safe")
  expect_named(formals(methods$declared), c(".mx_self", "renamed"))
  expect_identical(methods$implemented(obj, "careful"), "safe")
  expect_error(methods$implemented(obj), "missing")
  expect_identical(methods$named(obj), "safe")
  expect_identical(methods$named(obj, "careful"), "safe")
  expect_identical(methods$inferred(obj), 3L)
  expect_identical(methods$inferred(obj, 4), 4L)
})

test_that("empty and generic impls retain declaration parameter options", {
  obj <- ParameterOptions$new()
  methods <- ParameterOptions$ParameterDefault
  expect_identical(methods$inherited(obj), "safe")
  expect_identical(methods$inherited(obj, "f"), "fast")
  expect_identical(methods$checked(obj, 4), 4L)
  expect_error(methods$checked(obj, NA_real_), class = "rust_error")
  expect_identical(ParameterOptions$ParameterGeneric$generic_mode(obj), "fast")
  expect_identical(ParameterOptions$ParameterGeneric$generic_mode(obj, "careful"), "safe")
  expect_identical(ParameterOptions$ParameterGeneric$generic_default(obj), "fast")
  expect_identical(ParameterOptions$ParameterGeneric$generic_default(obj, "s"), "safe")
})
