# region: counting


def fold(lang, stats):
    """(code, blanks, lines) of one tokei report, embedded blobs included."""
    code, blanks = stats["code"], stats["blanks"]
    lines = code + blanks + stats["comments"]
    for blob_lang, blob in stats["blobs"].items():
        bc, bb, bl = fold(blob_lang, blob)
        lines += bl
        if lang != "Rust":  # Rust blobs are doc comments: no code, no blank lines
            code, blanks = code + bc, blanks + bb
    return code, blanks, lines


def count(root, repo, tokei):
    """Line counts of one checkout, as a dict; `errors` lists what keeps it from a report."""
    rules = PROFILES[repo]["rules"]
    tracked = subprocess.check_output(["git", "ls-files", "-z"], cwd=root, text=True).split("\0")
    tracked = [p for p in tracked if p and (root / p).is_file() and not (root / p).is_symlink()]
    kinds = {p: classify(p, rules) for p in tracked}

    errors = []
    staged = {}  # staged path -> (original path, kind, inline)
    n_items = n_decls = 0
    doc_examples = defaultdict(int)
    with tempfile.TemporaryDirectory(prefix="mx-loc-") as tmp:
        tmp = Path(tmp)

        def stage(sub, path, kind, inline, content=None):
            dest = tmp / sub / path
            dest.parent.mkdir(parents=True, exist_ok=True)
            if content is None:
                shutil.copyfile(root / path, dest)
            else:
                dest.write_text(content)
            staged[f"{sub}/{path}"] = (path, kind, inline)

        for path in tracked:
            kind = kinds[path] or "unclassified"
            if not path.endswith(".rs"):
                stage(kind, path, kind, False)
                continue
            text = (root / path).read_text(errors="replace")
            doc_examples[kind] += doc_example_lines(text)
            regions = test_regions(text) if kind in ("library", "fixtures") else []
            if not regions:
                stage(kind, path, kind, False)
                continue
            lines = text.split("\n")
            in_test = set()
            for first, last, out_of_line in regions:
                in_test.update(range(first, last + 1))
                n_decls += bool(out_of_line)
                n_items += not out_of_line
                if out_of_line:
                    files = [c for c in mod_file_candidates(path, out_of_line) if c in kinds]
                    if files and kinds[files[0]] != "tests":
                        errors.append(f"{files[0]}: #[cfg(test)] module classified as "
                                      f"{kinds[files[0]]}; add a tests rule")
            rest = "\n".join(l for n, l in enumerate(lines) if n not in in_test)
            test = "\n".join(l for n, l in enumerate(lines) if n in in_test) + "\n"
            stage(kind, path, kind, False, rest)
            stage("inline", path, "tests", True, test)

        out = subprocess.check_output(
            [tokei, "--output", "json", "--no-ignore", "--hidden", "."], cwd=tmp, text=True)

        by_kind = defaultdict(lambda: [0, 0, 0, 0])  # files, code, comments, blanks
        by_component = defaultdict(lambda: defaultdict(int))
        by_language = defaultdict(lambda: defaultdict(int))
        inline_code = 0
        for lang, data in json.loads(out).items():
            if lang == "Total":
                continue
            for r in data["reports"]:
                name = r["name"].removeprefix("./")
                path, kind, inline = staged[name]
                if kind == "unclassified":
                    errors.append(f"{path}: no rule in PROFILES[{repo!r}] covers this file")
                    continue
                code, blanks, lines = fold(lang, r["stats"])
                text = (tmp / name).read_text(errors="replace")
                physical = text.count("\n") + (bool(text) and not text.endswith("\n"))
                if lines > physical:
                    errors.append(f"{path}: tokei counted {lines} lines of {physical}")
                row = by_kind[kind]
                row[0] += not inline  # a split file counts once, in its own kind
                row[1] += code
                row[2] += physical - code - blanks
                row[3] += blanks
                by_component[component(path, repo)][kind] += code
                by_language[lang][kind] += code
                inline_code += code if inline else 0

    return dict(by_kind=by_kind, by_component=by_component, by_language=by_language,
                inline_code=inline_code, n_items=n_items, n_decls=n_decls, doc_examples=doc_examples,
                errors=errors)


def refuse(repo, errors):
    print(f"loc: refusing to report {repo}; fix these first:", file=sys.stderr)
    for e in errors:
        print(f"  {e}", file=sys.stderr)
    sys.exit(1)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--compare", action="store_true",
                    help="also clone and count " + " and ".join(r for r in PROFILES if PROFILES[r]["url"]))
    args = ap.parse_args()

    tokei = shutil.which("tokei")
    if tokei is None:
        sys.exit("loc: tokei not found; install it with `cargo install tokei`")
    root = Path(subprocess.check_output(["git", "rev-parse", "--show-toplevel"], text=True).strip())

    if not args.compare:
        counts = count(root, "miniextendr", tokei)
        if counts["errors"]:
            refuse("miniextendr", counts["errors"])
        report(counts)
        return

    results = []
    with tempfile.TemporaryDirectory(prefix="mx-loc-repos-") as clones:
        for repo, profile in PROFILES.items():
            checkout = root
            if profile["url"]:
                checkout = Path(clones) / repo
                subprocess.run(["git", "clone", "--quiet", "--depth", "1", profile["url"], str(checkout)],
                               check=True)
            commit = subprocess.check_output(["git", "rev-parse", "--short", "HEAD"], cwd=checkout,
                                             text=True).strip()
            counts = count(checkout, repo, tokei)
            if counts["errors"]:
                refuse(repo, counts["errors"])
            results.append((repo, commit, counts))
    compare(results)


