#!/usr/bin/env python3
"""Count lines of code by kind (library, tests, test fixtures, ...) with tokei.

Usage:
  python3 scripts/loc.py            miniextendr by kind, component and language (`just loc`)
  python3 scripts/loc.py --compare  miniextendr next to extendr and savvy (`just loc-compare`)

Counts the working-tree contents of git-tracked files; `--compare` clones the
default branch of each other repository (shallow) into a temporary directory.
tokei does the code/comment/blank split. Every file gets a kind from its
repository's rules in PROFILES (first match wins), and a file tokei counts that
no rule covers is an error, so a new directory has to be placed on purpose.

Inside library and fixture `.rs` files, every item under `#[cfg(test)]` (or
`cfg(all(test, ..))`) or `#[test]` is cut out and counted as tests, so a
repository that keeps its unit tests inline counts the same as one that keeps
them in tests.rs files, as miniextendr does (`just inline-tests-check`).

Comments are the lines that are neither code nor blank, so Rust doc comments
(`///`, `//!`) count as comments, runnable doc examples included; the reports
give those separately. tokei reports doc comments as Markdown blobs, which drop
each doc block's trailing empty `///` line.
"""

