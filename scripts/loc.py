# region: reports


def n(x):
    return f"{x:,}"


def table(header, rows, widths):
    fmt = "  ".join(f"{{:{'<' if i == 0 else '>'}{w}}}" for i, w in enumerate(widths))
    print(fmt.format(*header))
    print("-" * (sum(widths) + 2 * (len(widths) - 1)))
    for r in rows:
        print(fmt.format(*r))


def ratios(by_kind):
    lib, tests, fixtures = (by_kind[k][1] for k in ("library", "tests", "fixtures"))
    return tests / lib, (tests + fixtures) / lib


def report(c):
    by_kind = c["by_kind"]
    print("Lines by kind (git-tracked files, counted by tokei)\n")
    rows = []
    total = [0, 0, 0, 0]
    for kind in CODE_KINDS:
        rows.append([kind, *map(n, by_kind[kind]), KINDS[kind]])
        total = [a + b for a, b in zip(total, by_kind[kind])]
    rows.append(["total", *map(n, total), ""])
    for kind in ("docs", "generated"):
        rows.append([kind, *map(n, by_kind[kind]), KINDS[kind]])
    table(["kind", "files", "code", "comments", "blanks", ""], rows, [10, 6, 9, 9, 8, 0])

    tests, with_fixtures = ratios(by_kind)
    print(f"\ntests include {n(c['inline_code'])} code lines cut out of library and fixture .rs files: "
          f"{n(c['n_items'])} #[cfg(test)]/#[test] items, {n(c['n_decls'])} `mod tests;` declarations.")
    print(f"library comments include {n(c['doc_examples']['library'])} lines of runnable doc examples.")
    print(f"Test code per library code line: tests {tests:.2f}, tests + fixtures {with_fixtures:.2f}.\n")

    cols = ["library", "tests", "fixtures", "benches"]
    print("Code lines by component\n")
    rows = []
    for comp, counts in sorted(c["by_component"].items(), key=lambda kv: -sum(kv[1][k] for k in cols)):
        if any(counts[k] for k in cols):
            rows.append([comp, *(n(counts[k]) for k in cols)])
    table(["component", *cols], rows, [26, 9, 9, 9, 9])
    print("\nrpkg's testthat suite and fixtures exercise miniextendr-api and -macros, so a\n"
          "per-component tests/library ratio would say where tests live, not what they cover.")

    print("\nCode lines by language\n")
    rows = []
    for lang, counts in sorted(c["by_language"].items(), key=lambda kv: -sum(kv[1][k] for k in cols)):
        if any(counts[k] for k in cols):
            rows.append([lang, *(n(counts[k]) for k in cols)])
    table(["language", *cols], rows, [26, 9, 9, 9, 9])


def compare(results):
    names = [r[0] for r in results]
    print("Code lines by kind (tokei; #[cfg(test)] items count as tests)\n")
    rows = [["commit", *(commit for _, commit, _ in results)]]
    for kind in CODE_KINDS:
        rows.append([kind, *(n(c["by_kind"][kind][1]) for _, _, c in results)])
    pairs = [ratios(c["by_kind"]) for _, _, c in results]
    rows.append(["tests per library line", *(f"{t:.2f}" for t, _ in pairs)])
    rows.append(["  with fixtures", *(f"{f:.2f}" for _, f in pairs)])
    rows.append(["library comment lines", *(n(c["by_kind"]["library"][2]) for _, _, c in results)])
    rows.append(["  runnable doc examples", *(n(c["doc_examples"]["library"]) for _, _, c in results)])
    table(["", *names], rows, [24, *(max(11, len(x)) for x in names)])

    print("\nRunnable doc examples are doctests, counted in comments, not tests.\n")
    print("Library code lines by component\n")
    for repo, _, c in results:
        parts = sorted(((comp, k["library"]) for comp, k in c["by_component"].items() if k["library"]),
                       key=lambda p: -p[1])
        print(f"  {repo}: " + ", ".join(f"{comp} {n(v)}" for comp, v in parts))


