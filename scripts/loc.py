def classify(path, rules):
    for pattern, kind in rules:
        if fnmatch.fnmatchcase(path, pattern):
            return kind
    return None


def component(path, repo):
    """The top-level directory; files at the root and under src/ belong to the repository's own crate."""
    parts = path.split("/")
    if len(parts) == 1 or parts[0] == "src":
        return repo
    if parts[0] == "tests" and len(parts) > 2:
        return "/".join(parts[:2])
    return parts[0]


