# region: runnable doc examples

DOC_LINE = re.compile(r"\s*//[/!]\s?(.*)")
NOT_RUN = ("ignore", "no_run", "compile_fail", "text")


def doc_example_lines(text):
    """Lines inside runnable code blocks of doc comments (the doctests)."""
    count, inside, runnable = 0, False, False
    for line in text.split("\n"):
        m = DOC_LINE.match(line)
        if m is None:
            inside = False
            continue
        body = m.group(1).lstrip()
        if body.startswith("```"):
            if not inside:
                tag = body[3:].strip()
                runnable = tag == "" or (tag.startswith("rust") and not any(t in tag for t in NOT_RUN))
            inside = not inside
        elif inside and runnable:
            count += 1
    return count


