# region: Rust test regions

TOKEN = re.compile(
    r"""
    (?P<comment>//[^\n]*)
  | (?P<block>/\*)
  | (?P<raw>[bc]?r\#*")
  | (?P<str>[bc]?")
  | (?P<char>b?'(?:\\(?:x[0-9a-fA-F]{2}|u\{[0-9a-fA-F]{1,6}\}|.)|[^\\'\n])')
  | (?P<lifetime>'[A-Za-z_]\w*)
  | (?P<ident>[A-Za-z_]\w*)
  | (?P<space>\s+)
  | (?P<punct>.)
    """,
    re.X | re.S,
)
STR_BODY = re.compile(r'(?:[^"\\]|\\.)*"', re.S)
BLOCK_DELIM = re.compile(r"/\*|\*/")
OPEN, CLOSE = "([{", ")]}"


def tokens(text):
    """Code tokens as (start, end, kind); comments and whitespace are dropped."""
    out = []
    pos, n = 0, len(text)
    while pos < n:
        m = TOKEN.match(text, pos)
        kind, end = m.lastgroup, m.end()
        if kind == "block":
            depth = 1
            while depth:
                d = BLOCK_DELIM.search(text, end)
                if d is None:
                    end = n
                    break
                depth += 1 if d.group() == "/*" else -1
                end = d.end()
        elif kind == "raw":
            close = '"' + "#" * m.group().count("#")
            found = text.find(close, end)
            end = n if found < 0 else found + len(close)
        elif kind == "str":
            s = STR_BODY.match(text, end)
            end = n if s is None else s.end()
        if kind not in ("comment", "block", "space"):
            out.append((m.start(), end, kind))
        pos = end
    return out


def is_test_attr(inner):
    inner = re.sub(r"\s+", "", inner)
    if inner in ("test", "cfg(test)"):
        return True
    m = re.fullmatch(r"cfg\(all\((.*)\)\)", inner)
    return bool(m) and "test" in m.group(1).split(",")


def matching(text, toks, j):
    """Index of the token that closes the bracket opened at toks[j]."""
    depth = 0
    for k in range(j, len(toks)):
        if toks[k][2] == "punct":
            c = text[toks[k][0]]
            depth += (c in OPEN) - (c in CLOSE)
            if depth == 0:
                return k
    return len(toks) - 1


def item_end(text, toks, j):
    """Index of the last token of the item that starts at toks[j]."""
    depth = 0
    for k in range(j, len(toks)):
        if toks[k][2] != "punct":
            continue
        c = text[toks[k][0]]
        if c in OPEN:
            depth += 1
        elif c in CLOSE:
            if depth == 0:  # the enclosing block closed: the item ran to its end
                return k - 1
            depth -= 1
            if depth == 0 and c == "}":
                if k + 1 < len(toks) and text[toks[k + 1][0]] == ";":
                    return k + 1
                return k
        elif c in ";," and depth == 0:
            return k
    return len(toks) - 1


def test_regions(text):
    """Test-only items as (first_line, last_line, out_of_line_mod), 0-based and inclusive."""
    toks = tokens(text)
    lines = text.split("\n")
    line_starts = [0]
    for line in lines[:-1]:
        line_starts.append(line_starts[-1] + len(line) + 1)

    def line_of(offset):
        return bisect.bisect_right(line_starts, offset) - 1

    regions = []
    i = 0
    while i < len(toks):
        start, _, kind = toks[i]
        if not (kind == "punct" and text[start] == "#" and i + 1 < len(toks)
                and text[toks[i + 1][0]] == "["):
            i += 1
            continue
        close = matching(text, toks, i + 1)  # the attribute's `]`
        inner = text[toks[i + 1][1]:toks[close][0]]
        if not is_test_attr(inner):
            i += 1
            continue
        last = item_end(text, toks, close + 1)
        first_line, last_line = line_of(start), line_of(toks[last][1] - 1)
        before = text[line_starts[first_line]:start]
        after = text[toks[last][1]:].split("\n", 1)[0].strip()
        if before.strip() or (after and not after.startswith("//")):
            i = last + 1  # shares a line with library code: leave it counted as library
            continue
        while first_line > 0 and re.match(r"\s*(#\[.*\]|///)", lines[first_line - 1]):
            first_line -= 1
        words = [text[s:e] for s, e, k in toks[close + 1:last + 1] if k in ("ident", "punct")]
        out_of_line = None
        if len(words) >= 3 and words[-1] == ";" and words[-3] == "mod":
            out_of_line = words[-2]
        regions.append((first_line, last_line, out_of_line))
        i = last + 1
    return regions


def mod_file_candidates(path, name):
    p = Path(path)
    base = p.parent if p.name in ("lib.rs", "main.rs", "mod.rs") else p.parent / p.stem
    return [str(base / f"{name}.rs"), str(base / name / "mod.rs")]


