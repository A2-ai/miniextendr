#!/usr/bin/env bash
# Compile-check the Rust examples in docs/ and in the end-user Claude skills.
#
# A fenced ```rust block is checked when the line right before its fence is
#
#   <!-- docs-examples-check -->
#
# Each marked block becomes a module of a scratch crate under
# <target>/docs-examples, and `cargo check` builds it against this
# checkout's miniextendr-api. Blocks that share a name, as in
#
#   <!-- docs-examples-check: quickstart -->
#
# go into one module in document order, so a later block can use what an
# earlier one defines. Nothing is added to a block: it brings its own `use`
# lines, so a missing import fails here as it would for a reader.
#
# The module file starts with a `// <doc>:<line>` comment naming the doc line
# of the block's first code line; line N of the module file is that doc line
# plus N - 2.
#
# Usage: scripts/docs-examples-check.sh [file.md ...]
#   (default: docs/*.md and minirextendr/inst/claude/skills/*/SKILL.md)
# Needs R, like every miniextendr-api build (its build.rs runs `R RHOME`).
set -euo pipefail

repo="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
target="${CARGO_TARGET_DIR:-$repo/target}"
crate="$target/docs-examples"

if [ "$#" -gt 0 ]; then
  files=("$@")
else
  files=("$repo"/docs/*.md "$repo"/minirextendr/inst/claude/skills/*/SKILL.md)
fi

rm -rf "$crate/src"
mkdir -p "$crate/src"

# Writes src/<module>.rs for every marked block and prints each new module name.
modules="$(awk -v src="$crate/src" -v repo="$repo/" '
  function rel(file) {
    return index(file, repo) == 1 ? substr(file, length(repo) + 1) : file
  }
  function fail(msg) {
    printf "%s\n", msg > "/dev/stderr"
    bad = 1
  }
  FNR == 1 {
    if (inblock) fail(prev ": unterminated ```rust block")
    if (pending) fail(prev ": docs-examples-check marker at the end of the file")
    inblock = 0; pending = 0
  }
  { prev = FILENAME }
  inblock && /^```[[:space:]]*$/ { inblock = 0; close(path); next }
  inblock { print >> path; next }
  pending && /^```rust[[:space:]]*$/ {
    m = rel(FILENAME) "_" (group == "" ? "l" (FNR + 1) : group)
    m = "ex_" tolower(m)
    gsub(/[^a-z0-9_]/, "_", m)
    path = src "/" m ".rs"
    if (!(m in seen)) { seen[m] = 1; print m }
    print "// " rel(FILENAME) ":" (FNR + 1) >> path
    inblock = 1; pending = 0
    next
  }
  pending {
    fail(rel(FILENAME) ":" (FNR - 1) ": docs-examples-check marker not followed by a ```rust fence")
    pending = 0
  }
  /^<!-- docs-examples-check(: *[A-Za-z0-9_-]+)? *-->[[:space:]]*$/ {
    group = $0
    sub(/^<!-- docs-examples-check:? */, "", group)
    sub(/ *-->.*$/, "", group)
    pending = 1
  }
  END {
    if (inblock) fail(prev ": unterminated ```rust block")
    if (pending) fail(prev ": docs-examples-check marker at the end of the file")
    exit bad
  }
' "${files[@]}")"

if [ -z "$modules" ]; then
  echo "docs-examples-check: no marked blocks in ${files[*]}" >&2
  exit 1
fi

{
  echo "//! Generated by scripts/docs-examples-check.sh; do not edit."
  echo "#![allow(unused)]"
  while read -r m; do echo "mod $m;"; done <<<"$modules"
} >"$crate/src/lib.rs"

cat >"$crate/Cargo.toml" <<EOF
[package]
name = "docs-examples"
version = "0.0.0"
edition = "2024"
publish = false

[dependencies]
miniextendr-api = { path = "$repo/miniextendr-api" }

# Its own workspace, so the repository workspace and its Cargo.lock stay as
# they are. The copied lock pins the dependencies to the repository's versions.
[workspace]
EOF
cp "$repo/Cargo.lock" "$crate/Cargo.lock"

echo "docs-examples-check: $(wc -l <<<"$modules" | tr -d ' ') example modules"
cargo check --quiet --manifest-path "$crate/Cargo.toml" --target-dir "$target"
