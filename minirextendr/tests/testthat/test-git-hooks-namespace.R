# Tests for the stale-NAMESPACE check in inst/hooks/pre-commit.
#
# Most Rust edits change only the source-line comments and the header hash of
# R/*-wrappers.R, which leave NAMESPACE as it is. The hook blocks a staged
# wrappers file only when NAMESPACE has unstaged changes, or when NAMESPACE is
# not staged and the namespace tags (each with the object its block
# documents) differ between HEAD's and the staged copies of the staged R/
# files, the wrappers and the hand-written ones together, so a tag that moves
# from a hand-written file into the wrappers changes nothing.

skip_if_no_git_or_bash <- function() {
  if (Sys.which("git") == "") testthat::skip("git not available")
  if (Sys.which("bash") == "") testthat::skip("bash not available")
}

# Setup-only git call: a failure here would let a test pass for the wrong
# reason, so stop instead of returning the status.
git <- function(repo, ...) {
  args <- c("-C", repo, ...)
  status <- system2("git", shQuote(args), stdout = FALSE, stderr = FALSE)
  if (status != 0L) stop("git ", paste(args, collapse = " "), " failed")
  invisible(status)
}

# A generated wrappers file. `line` moves every source location and the
# header hash, as a Rust body or doc-comment edit does; `export_add` drops
# the @export of `add`; `method` and `s3` are the @method and
# @exportS3Method targets; `extra` is appended.
wrappers_lines <- function(line = 10L, export_add = TRUE, method = "print Thing",
                           s3 = "base::format", extra = character()) {
  c(
    "# ---- AUTO-GENERATED FILE - DO NOT EDIT ----",
    sprintf("# miniextendr-api 0.1.0 | fnv1a-64 of the normalized lines below: %016x", line),
    "# nolint start",
    "",
    sprintf("# Generated from Rust fn `add` (lib.rs:%d:1)", line),
    "#' Add two numbers",
    "#' @param a,b Numbers.",
    if (export_add) "#' @export",
    "add <- function(a, b) {",
    "  .Call(C_add, a, b)",
    "}",
    "",
    sprintf("# Generated from Rust fn `print_thing` (lib.rs:%d:1)", line + 5L),
    "#' Print a Thing",
    "#' @param x A Thing.",
    "#' @param ... Unused.",
    paste("#' @method", method),
    "#' @export",
    "print.Thing <- function(x, ...) {",
    "  .Call(C_print_thing, x)",
    "}",
    "",
    "#' Format a Thing",
    paste("#' @exportS3Method", s3),
    "format.Thing <- function(x, ...) \"thing\"",
    "",
    "#' @title Thing helpers",
    "#' @name thing_helpers",
    "#' @rawNamespace export(thing_helper)",
    "NULL",
    extra
  )
}

# A hand-written R file: `info` with its @export (`export_info = FALSE` drops
# the tag, `info = FALSE` the function), and an unexported `helper`.
hand_lines <- function(info = TRUE, export_info = TRUE) {
  c(
    if (info) c(
      "#' Information about a result",
      "#' @param x A result.",
      if (export_info) "#' @export",
      "info <- function(x) x",
      ""
    ),
    "# Not exported.",
    "helper <- function() NULL"
  )
}

# The wrappers block of `info` once a Rust function replaces the R one.
info_wrapper <- c(
  "",
  "# Generated from Rust fn `info` (lib.rs:30:1)",
  "#' Information about a result",
  "#' @param x A result.",
  "#' @export",
  "info <- function(x) {",
  "  .Call(C_info, x)",
  "}"
)

# Fake miniextendr package under `pkg_dir` in a fresh git repo with a first
# commit of `wrappers`, `hand` as the hand-written R/commands.R when given,
# and NAMESPACE. `pkg_dir = "."` is a standalone package, `"rpkg"` a monorepo
# R package subdirectory. Plain tempfile + dir.create so the dir outlives
# this helper's frame.
make_ns_repo <- function(pkg_dir = ".", wrappers = wrappers_lines(), hand = NULL) {
  repo <- tempfile("namespace-hook-")
  pkg <- file.path(repo, pkg_dir)
  dir.create(file.path(pkg, "src", "rust"), recursive = TRUE)
  dir.create(file.path(pkg, "R"))
  writeLines(c("Package: testpkg", "Version: 0.1.0"), file.path(pkg, "DESCRIPTION"))
  writeLines(c(
    '[package]', 'name = "testpkg"', 'version = "0.1.0"', 'edition = "2021"'
  ), file.path(pkg, "src", "rust", "Cargo.toml"))
  writeLines(wrappers, file.path(pkg, "R", "testpkg-wrappers.R"))
  if (!is.null(hand)) writeLines(hand, file.path(pkg, "R", "commands.R"))
  writeLines(c("# Generated by roxygen2: do not edit by hand", "",
               "S3method(base::format,Thing)", "S3method(print,Thing)",
               "export(add)", "export(thing_helper)"),
             file.path(pkg, "NAMESPACE"))
  git(repo, "init", "-q")
  # Quiet identity so commits don't fail in CI sandboxes.
  git(repo, "config", "user.email", "test@example.com")
  git(repo, "config", "user.name", "Test")
  git(repo, "add", "-A")
  git(repo, "-c", "commit.gpgsign=false", "-c", "core.hooksPath=/dev/null",
      "commit", "-q", "-m", "init")
  repo
}

# Write `lines` as the package's wrappers file and stage it.
stage_wrappers <- function(repo, lines, pkg_dir = ".") {
  stage_r_file(repo, "testpkg-wrappers.R", lines, pkg_dir)
}

# Write `lines` as the package's R/<name> and stage it.
stage_r_file <- function(repo, name, lines, pkg_dir = ".") {
  rel <- file.path(pkg_dir, "R", name)
  writeLines(lines, file.path(repo, rel))
  git(repo, "add", rel)
}

# Run the bundled hook in `repo` with whatever is currently staged.
run_hook <- function(repo) {
  hook_path <- system.file("hooks", "pre-commit", package = "minirextendr", mustWork = TRUE)
  withr::with_dir(repo, {
    # The hook exits non-zero on an intentional block; suppress R's warning.
    suppressWarnings(system2("bash", hook_path, stdout = TRUE, stderr = TRUE))
  })
}

hook_status <- function(out) {
  status <- attr(out, "status")
  if (is.null(status)) 0L else status
}

expect_hook_pass <- function(out) {
  expect_identical(hook_status(out), 0L, info = paste(out, collapse = "\n"))
  expect_false(any(grepl("BLOCKED", out, fixed = TRUE)), info = paste(out, collapse = "\n"))
}

# The hook blocked on changed namespace tags and listed each of `changes`.
expect_tags_block <- function(out, changes) {
  text <- paste(out, collapse = "\n")
  expect_identical(hook_status(out), 1L, info = text)
  expect_match(text, "BLOCKED: the staged R/ files change the namespace tags", fixed = TRUE)
  for (change in changes) expect_match(text, change, fixed = TRUE)
}

test_that("moved source lines with an unchanged tag set pass", {
  skip_if_no_git_or_bash()
  repo <- make_ns_repo()
  on.exit(unlink(repo, recursive = TRUE), add = TRUE)
  stage_wrappers(repo, wrappers_lines(line = 42L))

  out <- run_hook(repo)
  expect_hook_pass(out)
  expect_true(any(grepl("all miniextendr checks passed", out, fixed = TRUE)))
})

test_that("an added @export blocks", {
  skip_if_no_git_or_bash()
  repo <- make_ns_repo()
  on.exit(unlink(repo, recursive = TRUE), add = TRUE)
  stage_wrappers(repo, wrappers_lines(
    extra = c("", "#' Subtract", "#' @export", "sub <- function(a, b) a - b")
  ))

  expect_tags_block(run_hook(repo), "added:   @export (sub)")
})

test_that("a removed @export blocks", {
  skip_if_no_git_or_bash()
  repo <- make_ns_repo()
  on.exit(unlink(repo, recursive = TRUE), add = TRUE)
  stage_wrappers(repo, wrappers_lines(export_add = FALSE))

  expect_tags_block(run_hook(repo), "removed: @export (add)")
})

test_that("a changed @method or @exportS3Method target blocks", {
  skip_if_no_git_or_bash()
  repo <- make_ns_repo()
  on.exit(unlink(repo, recursive = TRUE), add = TRUE)

  stage_wrappers(repo, wrappers_lines(method = "print Other"))
  expect_tags_block(run_hook(repo), c(
    "added:   @method print Other (print.Thing)",
    "removed: @method print Thing (print.Thing)"
  ))

  stage_wrappers(repo, wrappers_lines(s3 = "pkg::format"))
  expect_tags_block(run_hook(repo), c(
    "added:   @exportS3Method pkg::format (format.Thing)",
    "removed: @exportS3Method base::format (format.Thing)"
  ))
})

test_that("a renamed object behind an unchanged tag blocks", {
  # The tag text stays `@export`; what NAMESPACE exports is the object.
  skip_if_no_git_or_bash()
  repo <- make_ns_repo()
  on.exit(unlink(repo, recursive = TRUE), add = TRUE)
  lines <- wrappers_lines()
  lines <- sub("^add <- function", "plus <- function", lines)
  stage_wrappers(repo, lines)

  expect_tags_block(run_hook(repo), c("added:   @export (plus)", "removed: @export (add)"))
})

test_that("a staged deletion of the wrappers file blocks", {
  skip_if_no_git_or_bash()
  repo <- make_ns_repo()
  on.exit(unlink(repo, recursive = TRUE), add = TRUE)
  git(repo, "rm", "-q", "--cached", "R/testpkg-wrappers.R")

  expect_tags_block(run_hook(repo), c("removed: @export (add)", "removed: @rawNamespace export(thing_helper) (thing_helpers)"))
})

test_that("unstaged NAMESPACE changes block", {
  skip_if_no_git_or_bash()
  repo <- make_ns_repo()
  on.exit(unlink(repo, recursive = TRUE), add = TRUE)
  # The tag set is unchanged, so only the unstaged NAMESPACE blocks.
  stage_wrappers(repo, wrappers_lines(line = 42L))
  cat("export(sub)\n", file = file.path(repo, "NAMESPACE"), append = TRUE)

  out <- run_hook(repo)
  text <- paste(out, collapse = "\n")
  expect_identical(hook_status(out), 1L, info = text)
  expect_match(text, "BLOCKED: R/*-wrappers.R is staged, but NAMESPACE has unstaged changes.", fixed = TRUE)
  expect_match(text, "git add NAMESPACE man", fixed = TRUE)
})

test_that("unstaged NAMESPACE changes block under a monorepo prefix", {
  skip_if_no_git_or_bash()
  repo <- make_ns_repo("rpkg")
  on.exit(unlink(repo, recursive = TRUE), add = TRUE)
  stage_wrappers(repo, wrappers_lines(line = 42L), pkg_dir = "rpkg")
  cat("export(sub)\n", file = file.path(repo, "rpkg", "NAMESPACE"), append = TRUE)

  out <- run_hook(repo)
  text <- paste(out, collapse = "\n")
  expect_identical(hook_status(out), 1L, info = text)
  expect_match(text, "rpkg/NAMESPACE has unstaged changes", fixed = TRUE)
  expect_match(text, "git add rpkg/NAMESPACE rpkg/man", fixed = TRUE)
})

test_that("changed tags under a monorepo prefix block", {
  skip_if_no_git_or_bash()
  repo <- make_ns_repo("rpkg")
  on.exit(unlink(repo, recursive = TRUE), add = TRUE)
  stage_wrappers(repo, wrappers_lines(export_add = FALSE), pkg_dir = "rpkg")

  out <- run_hook(repo)
  expect_tags_block(out, "removed: @export (add)")
  expect_match(paste(out, collapse = "\n"), "rpkg/NAMESPACE was not updated", fixed = TRUE)
})

test_that("a NAMESPACE staged together with the wrappers passes", {
  skip_if_no_git_or_bash()
  repo <- make_ns_repo()
  on.exit(unlink(repo, recursive = TRUE), add = TRUE)
  stage_wrappers(repo, wrappers_lines(
    extra = c("", "#' Subtract", "#' @export", "sub <- function(a, b) a - b")
  ))
  cat("export(sub)\n", file = file.path(repo, "NAMESPACE"), append = TRUE)
  git(repo, "add", "NAMESPACE")

  expect_hook_pass(run_hook(repo))
})

test_that("an @export moved from a hand-written file into the wrappers passes", {
  # An R function replaced by a Rust one: devtools::document() leaves
  # NAMESPACE as it is, so the commit has none to stage.
  skip_if_no_git_or_bash()
  repo <- make_ns_repo(hand = hand_lines())
  on.exit(unlink(repo, recursive = TRUE), add = TRUE)
  stage_r_file(repo, "commands.R", hand_lines(info = FALSE))
  stage_wrappers(repo, wrappers_lines(line = 42L, extra = info_wrapper))

  expect_hook_pass(run_hook(repo))
})

test_that("an @export moved out of a deleted hand-written file passes", {
  # A deleted (or renamed: --no-renames splits it) file gives HEAD's tags.
  skip_if_no_git_or_bash()
  repo <- make_ns_repo(hand = hand_lines())
  on.exit(unlink(repo, recursive = TRUE), add = TRUE)
  git(repo, "rm", "-q", "R/commands.R")
  stage_wrappers(repo, wrappers_lines(line = 42L, extra = info_wrapper))

  expect_hook_pass(run_hook(repo))
})

test_that("an @export added to the wrappers blocks with a hand-written file staged", {
  skip_if_no_git_or_bash()
  repo <- make_ns_repo(hand = hand_lines())
  on.exit(unlink(repo, recursive = TRUE), add = TRUE)
  stage_r_file(repo, "commands.R", c(hand_lines(), "# A comment."))
  stage_wrappers(repo, wrappers_lines(
    extra = c("", "#' Subtract", "#' @export", "sub <- function(a, b) a - b")
  ))

  expect_tags_block(run_hook(repo), "added:   @export (sub)")
})

test_that("an @export removed from a hand-written file blocks", {
  # The wrappers change only in their source lines.
  skip_if_no_git_or_bash()
  repo <- make_ns_repo(hand = hand_lines())
  on.exit(unlink(repo, recursive = TRUE), add = TRUE)
  stage_r_file(repo, "commands.R", hand_lines(export_info = FALSE))
  stage_wrappers(repo, wrappers_lines(line = 42L))

  expect_tags_block(run_hook(repo), "removed: @export (info)")
})

test_that("a deleted hand-written file's @export blocks", {
  skip_if_no_git_or_bash()
  repo <- make_ns_repo(hand = hand_lines())
  on.exit(unlink(repo, recursive = TRUE), add = TRUE)
  git(repo, "rm", "-q", "R/commands.R")
  stage_wrappers(repo, wrappers_lines(line = 42L))

  expect_tags_block(run_hook(repo), "removed: @export (info)")
})

test_that("hand-written files are checked only with a staged wrappers file", {
  # The check guards regenerated wrappers; a package's own R edits alone are
  # left to it.
  skip_if_no_git_or_bash()
  repo <- make_ns_repo(hand = hand_lines())
  on.exit(unlink(repo, recursive = TRUE), add = TRUE)
  stage_r_file(repo, "commands.R", hand_lines(export_info = FALSE))

  expect_hook_pass(run_hook(repo))
})
